-- Durations are not published anywhere on the scraped pages (the JS player payload carries no
-- length field), so they have to be read out of the audio itself. That is expensive, so the
-- result is kept here forever: a track's length never changes, and the key is the same hrefHash
-- the band payload already exposes.
CREATE TABLE IF NOT EXISTS track_duration_entity
(
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    href_hash       varchar(255) NOT NULL UNIQUE,
    duration_ms     bigint,
    update_time     timestamp,
    PRIMARY KEY (id)
);
